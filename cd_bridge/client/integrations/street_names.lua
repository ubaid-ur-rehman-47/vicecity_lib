local function getTranslatedStreetName(coords)
    local streetHash = GetStreetNameAtCoord(coords.x, coords.y, coords.z)
    local localeKey = streetNames[streetHash]

    if localeKey then
        return Locale(localeKey)
    end

    return GetStreetNameFromHashKey(streetHash) or ''
end

local function getTranslatedZoneName(coords)
    local zone = GetNameOfZone(coords.x, coords.y, coords.z)
    if not zone then return '' end

    local localeKey = zoneNames[GetHashKey(zone)]

    if localeKey then
        return Locale(localeKey)
    end

    return ''
end

function GetStreetNames(coords)
    coords = coords or GetEntityCoords(PlayerPedId())

    return {
        streetName = getTranslatedStreetName(coords),
        zoneName = getTranslatedZoneName(coords)
    }
end